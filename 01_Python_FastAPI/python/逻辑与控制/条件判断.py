# 语法
# if condition
#   # 当condition 为 True 时执行这里的代码
#   # 注意这里的缩进 （通常是四个空格）
age=20
isAdult=age>=18
if isAdult:
   print("你已经是大人了")
else :
    print("你还只是孩子")
